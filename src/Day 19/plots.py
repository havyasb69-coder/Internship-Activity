import matplotlib.pyplot as plt

def simple_plot():
    x = [1, 2, 3, 4, 5]
    y = [2, 4, 6, 8, 10]

    plt.plot(x, y, marker='o')
    plt.title("Feature Branch Visualization")
    plt.xlabel("X values")
    plt.ylabel("Y values")
    plt.grid(True)
    plt.show()

if __name__ == "__main__":
    simple_plot()
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    
    